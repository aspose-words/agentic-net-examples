using System;
using System.IO;
using Aspose.Words;
using Aspose.Words.Loading;

public class Program
{
    public static void Main()
    {
        // Create a sample document and save it as PDF (input.pdf).
        Document sourceDoc = new Document();
        DocumentBuilder builder = new DocumentBuilder(sourceDoc);
        builder.Writeln("Sample PDF content generated by Aspose.Words.");
        string pdfPath = "input.pdf";
        sourceDoc.Save(pdfPath, SaveFormat.Pdf);

        // Load the PDF while ignoring password protection using PdfLoadOptions.
        PdfLoadOptions loadOptions = new PdfLoadOptions();
        // No password is set; the loader will ignore any password protection.
        Document loadedPdf = new Document(pdfPath, loadOptions);

        // Save the loaded document as DOCX.
        string docxPath = "output.docx";
        loadedPdf.Save(docxPath, SaveFormat.Docx);

        // Validate that the DOCX file was created.
        if (!File.Exists(docxPath))
        {
            throw new InvalidOperationException("Expected output DOCX was not created.");
        }

        // Clean up temporary files (optional).
        File.Delete(pdfPath);
    }
}
