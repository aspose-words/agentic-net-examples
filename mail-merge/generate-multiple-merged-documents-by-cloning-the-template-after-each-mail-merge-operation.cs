using System;
using System.IO;
using Aspose.Words;
using Aspose.Words.MailMerging;

public class Program
{
    public static void Main()
    {
        // Create a template document in memory.
        Document template = new Document();
        DocumentBuilder builder = new DocumentBuilder(template);

        // Insert merge fields into the template.
        builder.Writeln("Dear ");
        builder.InsertField("MERGEFIELD FirstName");
        builder.Write(" ");
        builder.InsertField("MERGEFIELD LastName");
        builder.Writeln(",");
        builder.Writeln("This is a test document generated by Aspose.Words.");

        // Define merge field names.
        string[] fieldNames = { "FirstName", "LastName" };

        // Define data for multiple merges.
        object[][] dataRows = new object[][]
        {
            new object[] { "John", "Doe" },
            new object[] { "Jane", "Smith" },
            new object[] { "Alice", "Johnson" }
        };

        // Ensure output directory exists.
        string outputDir = Directory.GetCurrentDirectory();
        Console.WriteLine($"Output directory: {outputDir}");

        // Perform a separate mail merge for each data row.
        for (int i = 0; i < dataRows.Length; i++)
        {
            // Clone the template to keep it unchanged for the next iteration.
            Document mergedDoc = (Document)template.Clone();

            // Execute the mail merge with the current data row.
            mergedDoc.MailMerge.Execute(fieldNames, dataRows[i]);

            // Remove any unused merge fields from the result.
            mergedDoc.MailMerge.CleanupOptions = MailMergeCleanupOptions.RemoveUnusedFields;

            // Save the merged document.
            string outputPath = Path.Combine(outputDir, $"MergedDocument{i + 1}.docx");
            mergedDoc.Save(outputPath);

            // Validate that the merged document contains the expected values.
            Document validationDoc = new Document(outputPath);
            string docText = validationDoc.GetText();

            foreach (object value in dataRows[i])
            {
                if (value == null) continue;
                string valStr = value.ToString();
                if (!docText.Contains(valStr))
                {
                    throw new InvalidOperationException($"Validation failed: merged document '{outputPath}' does not contain value '{valStr}'.");
                }
            }

            Console.WriteLine($"Successfully created and validated '{outputPath}'.");
        }

        Console.WriteLine("All documents have been generated and validated.");
    }
}
