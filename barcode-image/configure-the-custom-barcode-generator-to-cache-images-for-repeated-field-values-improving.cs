using System;
using System.Collections.Generic;
using System.IO;
using Aspose.Words;
using Aspose.Words.Fields;
using Aspose.Drawing;
using Aspose.BarCode.Generation;

public sealed class CustomBarcodeGenerator : IBarcodeGenerator
{
    // Cache keyed by barcode value (symbology is fixed to Code128 for this example).
    private static readonly Dictionary<string, byte[]> _cache = new Dictionary<string, byte[]>();

    // Generates barcode image, using cache for repeated values.
    public Stream GetBarcodeImage(Aspose.Words.Fields.BarcodeParameters parameters)
    {
        // Build a cache key using the barcode value.
        string key = parameters.BarcodeValue ?? string.Empty;

        // Return cached image if it exists.
        if (_cache.TryGetValue(key, out byte[] cachedBytes))
        {
            var cachedStream = new MemoryStream(cachedBytes);
            cachedStream.Position = 0;
            return cachedStream;
        }

        // For this example we assume CODE128; adjust mapping if other symbologies are needed.
        SymbologyEncodeType symbology = EncodeTypes.Code128;

        // Generate the barcode image.
        using (var ms = new MemoryStream())
        {
            using (var generator = new BarcodeGenerator(symbology, parameters.BarcodeValue))
            {
                // Set barcode and background colors.
                generator.Parameters.Barcode.BarColor = Color.Black;
                generator.Parameters.BackColor = Color.White;

                // Save as PNG.
                generator.Save(ms, BarCodeImageFormat.Png);
            }

            // Cache the generated bytes.
            byte[] imageBytes = ms.ToArray();
            _cache[key] = imageBytes;

            // Return a fresh stream positioned at the beginning.
            var resultStream = new MemoryStream(imageBytes);
            resultStream.Position = 0;
            return resultStream;
        }
    }

    // Legacy method delegates to the main implementation.
    public Stream GetOldBarcodeImage(Aspose.Words.Fields.BarcodeParameters parameters)
    {
        return GetBarcodeImage(parameters);
    }
}

public class Program
{
    public static void Main()
    {
        // Create a new blank document.
        Document doc = new Document();
        DocumentBuilder builder = new DocumentBuilder(doc);

        // Insert first barcode field.
        FieldDisplayBarcode field1 = (FieldDisplayBarcode)builder.InsertField(FieldType.FieldDisplayBarcode, true);
        field1.BarcodeType = "CODE128";
        field1.BarcodeValue = "1234567890";
        field1.ForegroundColor = "0x000000";
        field1.BackgroundColor = "0xFFFFFF";

        // Insert a second barcode field with the same value to demonstrate caching.
        builder.Writeln(); // Move to a new line.
        FieldDisplayBarcode field2 = (FieldDisplayBarcode)builder.InsertField(FieldType.FieldDisplayBarcode, true);
        field2.BarcodeType = "CODE128";
        field2.BarcodeValue = "1234567890";
        field2.ForegroundColor = "0x000000";
        field2.BackgroundColor = "0xFFFFFF";

        // Register the custom barcode generator for rendered outputs.
        doc.FieldOptions.BarcodeGenerator = new CustomBarcodeGenerator();

        // Update fields to render barcodes.
        doc.UpdateFields();

        // Save the document as PDF (rendered output).
        doc.Save("output.pdf");
    }
}
