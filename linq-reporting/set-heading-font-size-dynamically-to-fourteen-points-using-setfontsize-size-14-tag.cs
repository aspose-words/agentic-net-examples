using System;
using Aspose.Words;
using Aspose.Words.Reporting;

public class Model
{
    public string Title { get; set; } = string.Empty;
}

public class Program
{
    public static void Main()
    {
        // Paths for the template and the generated report.
        const string templatePath = "Template.docx";
        const string outputPath = "Report.docx";

        // Create a template document programmatically.
        Document templateDoc = new Document();
        DocumentBuilder builder = new DocumentBuilder(templateDoc);

        // Set the heading font size to 14 points dynamically.
        builder.Font.Size = 14;
        builder.Writeln("<<[model.Title]>>"); // LINQ Reporting placeholder for the heading.

        // Add a simple paragraph after the heading.
        builder.Font.Size = 11;
        builder.Writeln("This paragraph is generated by Aspose.Words LINQ Reporting Engine.");

        // Save the template to disk.
        templateDoc.Save(templatePath);

        // Load the template for report generation.
        Document doc = new Document(templatePath);

        // Prepare the data model.
        Model model = new Model { Title = "Dynamic Heading Set to 14 Points" };

        // Build the report using the LINQ Reporting engine.
        ReportingEngine engine = new ReportingEngine();
        engine.BuildReport(doc, model, "model");

        // Save the final report.
        doc.Save(outputPath);

        Console.WriteLine($"Report generated successfully: {outputPath}");
    }
}
