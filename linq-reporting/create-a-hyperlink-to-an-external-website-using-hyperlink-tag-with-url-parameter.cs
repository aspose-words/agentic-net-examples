using System;
using System.IO;
using System.Text;
using Aspose.Words;
using Aspose.Words.Reporting;

public class ReportModel
{
    public string Url { get; set; } = "https://www.example.com";
    public string LinkText { get; set; } = "Visit Example";
}

public class Program
{
    public static void Main()
    {
        // Register code page provider for Aspose.Words.
        Encoding.RegisterProvider(CodePagesEncodingProvider.Instance);

        // Prepare folders.
        string outputDir = Path.Combine(Directory.GetCurrentDirectory(), "output");
        Directory.CreateDirectory(outputDir);

        // Create template document.
        string templatePath = Path.Combine(outputDir, "Template.docx");
        var templateDoc = new Document();
        var builder = new DocumentBuilder(templateDoc);
        builder.Writeln("Below is a hyperlink generated by LINQ Reporting:");
        builder.Writeln("<<link [model.Url] [model.LinkText]>>");
        templateDoc.Save(templatePath);

        // Load template for reporting.
        var doc = new Document(templatePath);

        // Prepare data model.
        var model = new ReportModel();

        // Build report.
        var engine = new ReportingEngine();
        engine.BuildReport(doc, model, "model");

        // Save the generated report.
        string reportPath = Path.Combine(outputDir, "Report.docx");
        doc.Save(reportPath);
    }
}
